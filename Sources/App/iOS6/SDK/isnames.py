#!/usr/bin/env python3
"""Writes Swift's names for the Boolean properties of generated wrappers.

Swift names an Objective-C property with an `is…` getter after the getter
(`isHidden`, `isEnabled`), while Swift-iOS6's objcgen.py keeps the property's
name (`hidden`). For each `@ObjCProperty(getter: "isX") var x` in a wrapper
file, this writes `var isX`, which reads (and writes) `x`, in an extension of
the same protocol, so VLC's sources keep Swift's spelling.

usage: isnames.py <generated wrappers.swift> <module> <output.swift>
"""

import re
import sys

EXTENSION = re.compile(r"^extension (\w+Methods) \{")
PROPERTY = re.compile(r'^\s*@ObjCProperty\(getter: "(is\w+)"(, readonly: true)?\) public var (\w+): (.+)$')
DECLARED = re.compile(r"\b(?:var|func) (is\w+)\b")


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__.strip().splitlines()[-1])
    source, module, output = sys.argv[1:]
    text = open(source).read()
    declared = set(DECLARED.findall(text))

    aliases = {}  # protocol -> lines
    current = None
    for line in text.splitlines():
        match = EXTENSION.match(line)
        if match:
            current = match.group(1)
            continue
        if line.startswith("}"):
            current = None
            continue
        match = PROPERTY.match(line)
        if not match or current is None:
            continue
        getter, readonly, name, type_ = match.groups()
        if getter in declared or getter == name:
            continue
        if readonly:
            body = f"    public var {getter}: {type_} {{ {name} }}"
        else:
            body = (f"    public var {getter}: {type_} {{\n"
                    f"        get {{ {name} }}\n"
                    f"        nonmutating set {{ {name} = newValue }}\n"
                    f"    }}")
        aliases.setdefault(current, []).append(body)

    out = [f"// Swift's is… names for {module}'s Boolean properties, generated by SDK/isnames.py",
           "// from the module's wrappers. Don't edit: regenerate with SDK/generate.sh.", ""]
    for protocol in sorted(aliases):
        out.append(f"extension {protocol} {{")
        out.extend(aliases[protocol])
        out.append("}")
        out.append("")
    with open(output, "w") as handle:
        handle.write("\n".join(out))
    print(f"{module}: {sum(len(v) for v in aliases.values())} is… names", file=sys.stderr)


if __name__ == "__main__":
    main()
